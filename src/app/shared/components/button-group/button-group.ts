import { Component, ViewEncapsulation } from '@angular/core';

/**
 * Группирует несколько `Button` подряд под одной общей визуальной обводкой
 * (stream.Front#95) — карточки турниров/новостей: сброс + 2 тоггла (глаз/
 * сердце) под одной рамкой, отдельная кнопка-воронка фильтра рядом уже вне
 * группы (реальный фильтр-бар с макета — отдельная будущая задача, здесь
 * только сам механизм группировки).
 *
 * Технический подход: PrimeNG уже поставляет `<p-buttongroup>` с ровно такой
 * CSS-логикой (`@primeuix/styles/dist/buttongroup`) — убирает двойную границу
 * между соседними кнопками и обнуляет radius у "внутренних" кнопок, оставляя
 * скруглёнными только внешние края первой/последней. Не подошёл напрямую:
 * его селекторы (`.p-button:not(:last-child)`, `:first-of-type`,
 * `:last-of-type`) требуют, чтобы `<button>`-элементы были прямыми
 * DOM-соседями друг друга — а наш `Button` оборачивает `<button>` в
 * собственный `<app-button>`-хост, из-за чего каждый `<button>` внутри
 * своего хоста всегда единственный ребёнок (одновременно и first-, и
 * last-child), и правило просто не сработает. Ниже — те же самые правила,
 * повторенные на уровень выше: сиблингом становится сам `<app-button>`, его
 * `<button>` внутри достаётся дочерним комбинатором.
 *
 * `ViewEncapsulation.None` вместо `::ng-deep` (deprecated) — спроецированный
 * через `<ng-content>` `<app-button>` в любом случае несёт атрибут-скоуп
 * родительского шаблона (того места, где написан `<app-button>`), а не этого
 * компонента, так что обычный скоупнутый селектор здесь не сработал бы;
 * стили ограничены конкретным классом `.app-button-group`, а не глобальными
 * тегами, чтобы не протекать наружу.
 */
@Component({
  selector: 'app-button-group',
  imports: [],
  templateUrl: './button-group.html',
  styleUrl: './button-group.scss',
  encapsulation: ViewEncapsulation.None,
})
export class ButtonGroup {}
